namespace Mono.LLM.Agent.MultiAgent;

/// <summary>
/// 指定团队模式中子任务的执行方式。
/// </summary>
public enum TeamExecutionMode
{
    /// <summary>
    /// 并行执行：所有子任务同时开始，各自把产出写入共享工作区。
    /// </summary>
    /// <remarks>
    /// 吞吐量最高，适合彼此独立、互不依赖的子任务。
    /// 由于成员在启动时只能看到当时的快照，若后一个子任务必须基于前一个的具体内容，
    /// 应改用 <see cref="Sequential"/>。
    /// </remarks>
    Parallel,

    /// <summary>
    /// 顺序执行：子任务逐个进行，后执行者能看到此前所有成员的产出。
    /// </summary>
    /// <remarks>
    /// 适合有明确上下游关系的子任务，代价是总耗时随子任务数量线性增长。
    /// </remarks>
    Sequential
}
